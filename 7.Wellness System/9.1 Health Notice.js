// ต้องแสดงข้อความหรือไม่ (ยังไม่เคยยอมรับ หรือยอมรับเนื้อหารุ่นเก่า)
function needsNotice(storage) {
  try {
    const v = JSON.parse(storage.getItem(KEY) || 'null');
    return !(v && v.accepted === true && v.version === VERSION);
  } catch (e) {
    return true;
  }
}

function accept(storage, now = Date.now()) {
  try { storage.setItem(KEY, JSON.stringify({ version: VERSION, accepted: true, at: now })); return true; } catch (e) { return false; }
}

module.exports = { VERSION, KEY, NOTICE, needsNotice, accept };
